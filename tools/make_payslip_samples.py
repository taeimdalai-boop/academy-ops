def main(out):
    os.makedirs(out, exist_ok=True)
    wb = Workbook()
    ws = wb.active
    ws.title = "급여대장"
    ws.append(COMMON + PAY + DED + ["지급총액", "공제총액", "실지급액"])
    for no, name, title, birth, hired, kind, note, pay, ded in STAFF:
        email = f"{no.lower().replace('-', '')}@workflowlab.example"
        gross, deduct = sum(pay.values()), sum(ded.values())
        ws.append(["2026-09", date(2026, 10, 10), no, name, title, birth, hired, kind, email, note]
                  + [pay.get(k, 0) for k in PAY] + [ded.get(k, 0) for k in DED] + [gross, deduct, gross - deduct])
    path = os.path.join(out, "급여대장_2026-09.xlsx")
    wb.save(path)
    print("written:", path)


